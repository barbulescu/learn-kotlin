 *
 * JAVA ANALOGY — the port map (legacy construct → Kotlin feature → exercise):
 *
 *   Customer/LineItem/Order POJOs, ~150 lines     →  data class, 3 lines           (ex04)
 *   telescoping constructors                      →  default values in the ctor    (ex06)
 *   setters + leaked mutable List                 →  val + read-only List          (ex01, ex04)
 *   hand-rolled equals/hashCode/toString          →  generated by `data`           (ex04)
 *   "may be null" Javadoc on getEmail()           →  String? + ?. + let + ?:       (ex03, ex13)
 *   OrderUtils static utility class               →  top-level & extension funs    (ex07)
 *   price.multiply(...).divide(...) chains        →  BigDecimal * and / operators  (stdlib)
 *   compareTo(minimum) >= 0                       →  just >=                       (stdlib)
 *   grandTotal accumulator loop                   →  items.sumOf { }               (ex08, ex09)
 *   instanceof chain + casts + else-throw         →  sealed class + when           (ex11, ex05)
 *   Pending.INSTANCE singleton ritual             →  object Pending                (ex12)
 *   receipt() overloads ×3 + StringBuilder loop   →  defaults + templates
 *                                                    + joinToString { }            (ex02, ex06, ex08)
 *   stream().collect(groupingBy(reducing(...)))   →  groupBy + filter + sorted     (ex09, ex14)
