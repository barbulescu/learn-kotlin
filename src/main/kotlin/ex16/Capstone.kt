 *   corrupts the order for everyone else, the getter that leaks the internal list.
 *
 *   Money is BigDecimal throughout — never Double. In Java that turns every price
 *   formula into a .multiply(...).divide(...) chain; Kotlin's stdlib overloads the
 *   arithmetic operators for BigDecimal, so the same type reads like arithmetic here.
 *   (Bonus: Kotlin's BigDecimal `/` defaults to HALF_EVEN rounding, where Java's bare
 *   divide() throws ArithmeticException the day a quotient stops terminating.)
 *
 *   Your job: port the legacy program to the Kotlin below and make CapstoneTest pass.
 *   The data model is already ported (4 lines, right below — compare with the three
